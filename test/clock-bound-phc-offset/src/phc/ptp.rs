use clock_bound::daemon::time::Instant;
use std::fs::File;

use libc::c_uint;
use nix::{errno::Errno, ioctl_readwrite};
use std::os::unix::io::AsRawFd;

/// `PTP_SYS_OFFSET_EXTENDED2` ioctl call.
const PTP_SYS_OFFSET_EXTENDED2: u32 = 3_300_932_882;

/// Maximum number of samples supported within a single `PTP_SYS_OFFSET_EXTENDED2` ioctl call.
const PTP_MAX_SAMPLES: usize = 25;

#[repr(C)]
#[derive(Debug, Clone, Copy, Default)]
pub struct PtpClockTime {
    pub sec: i64,
    pub nsec: u32,
    pub reserved: u32,
}

#[repr(C)]
#[derive(Debug, Clone, Copy, Default)]
pub struct PtpSysOffsetExtended {
    /// Number of samples to collect
    pub n_samples: c_uint,
    /// Resevered
    pub rsv: [c_uint; 3],
    /// Array of samples in the form [pre-TS, PHC, post-TS ]
    pub ts: [[PtpClockTime; 3]; PTP_MAX_SAMPLES],
}

ioctl_readwrite!(
    ptp_sys_offset_extended2,
    b'=',
    PTP_SYS_OFFSET_EXTENDED2,
    PtpSysOffsetExtended
);

#[derive(Debug, Clone, Copy)]
pub struct PtpReader {
    phc_device_fd: i32,
    ptp_sys_offset_extended: PtpSysOffsetExtended,
}

impl PtpReader {
    /// Construct a new `PtpReader`. This is a one-time-use struct that allows
    /// a read from the specified PTP device file.
    pub fn new(phc_device_file: &File) -> Self {
        let phc_device_fd = phc_device_file.as_raw_fd();
        let ptp_sys_offset_extended = PtpSysOffsetExtended {
            n_samples: 1,
            ..Default::default()
        };
        Self {
            phc_device_fd,
            ptp_sys_offset_extended,
        }
    }

    /// Consuming function call to retrieve timestamp from PTP device.
    ///
    /// # Errors
    /// Returns an error if the PTP ioctl fails.
    pub fn ptp_get_time(mut self) -> Result<Instant, Errno> {
        // SAFETY: The ptp_sys_offset_extended2() function is generated by the
        // nix::ioctl_readwrite! macro and the call is safe because the arguments
        // are expected to be valid.  The file descriptor comes from a File
        // that had File::open() successfully called on the path, ensuring
        // that the file descriptor is valid.  The other argument provided to
        // the ptp_sys_offset_extended2() was created within this function
        // just above, and its definition matches the expected struct format.
        let _ = unsafe {
            ptp_sys_offset_extended2(self.phc_device_fd, &raw mut self.ptp_sys_offset_extended)
        }?;
        let phc = self.ptp_sys_offset_extended.ts[0][1];
        Ok(Instant::from_time(phc.sec, phc.nsec))
    }
}
